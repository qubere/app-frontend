#!/usr/bin/env node
// Regenerates the "GENERATED JOBS" block in configure-scheduler.sh from
// apps/custom/src/lib/admin/cronJobs.data.ts — the single source of truth
// for recurring backend jobs, also consumed by the admin dashboard
// (apps/custom/src/lib/admin/cronData.ts). This is what stops the dashboard
// listing and the actual Cloud Scheduler config from drifting apart again.
//
// Usage:
//   npx tsx infrastructure/gcp/generate-configure-scheduler.mjs         # write
//   npx tsx infrastructure/gcp/generate-configure-scheduler.mjs --check # verify, no write (used in CI)

import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { CRON_JOB_DEFINITIONS } from "../../apps/custom/src/lib/admin/cronJobs.data.ts";

const SCRIPT_PATH = join(dirname(fileURLToPath(import.meta.url)), "configure-scheduler.sh");
const BEGIN_MARKER = "# BEGIN GENERATED JOBS — do not edit by hand.";
const END_MARKER = "# END GENERATED JOBS";

function renderJobLines() {
  const lines = [
    BEGIN_MARKER,
    "# Generated by infrastructure/gcp/generate-configure-scheduler.mjs from",
    "# apps/custom/src/lib/admin/cronJobs.data.ts. Run",
    "# `npx tsx infrastructure/gcp/generate-configure-scheduler.mjs` after editing",
    "# that file, then commit the result.",
  ];

  for (const job of CRON_JOB_DEFINITIONS) {
    const { trigger } = job;
    if (trigger.kind === "cloud-run-job") {
      // The db-backup job is provisioned separately at the bottom of
      // configure-scheduler.sh (outside this block) via its own
      // upsert_backup_job call, since it isn't interleaved with the plain
      // HTTP jobs in the script's execution order.
      if (trigger.schedulerJobName !== "qubere-db-backup-schedule") lines.push("upsert_document_job");
      continue;
    }
    const methodSuffix = trigger.method === "GET" ? "" : ` ${trigger.method}`;
    lines.push(`upsert_job ${job.schedulerName} "${job.cronExpression}" ${trigger.path}${methodSuffix}`);
  }

  lines.push(END_MARKER);
  return lines.join("\n");
}

const current = readFileSync(SCRIPT_PATH, "utf8");
const beginIdx = current.indexOf(BEGIN_MARKER);
const endIdx = current.indexOf(END_MARKER);
if (beginIdx === -1 || endIdx === -1) {
  console.error(`Could not find ${BEGIN_MARKER} / ${END_MARKER} markers in ${SCRIPT_PATH}`);
  process.exit(1);
}

const before = current.slice(0, beginIdx);
const after = current.slice(endIdx + END_MARKER.length);
const generated = before + renderJobLines() + after;

const checkOnly = process.argv.includes("--check");
if (checkOnly) {
  if (generated !== current) {
    console.error(
      "infrastructure/gcp/configure-scheduler.sh is out of sync with apps/custom/src/lib/admin/cronJobs.data.ts.\n" +
        "Run: npx tsx infrastructure/gcp/generate-configure-scheduler.mjs",
    );
    process.exit(1);
  }
  console.log("OK: configure-scheduler.sh matches cronJobs.data.ts.");
} else {
  writeFileSync(SCRIPT_PATH, generated);
  console.log(`Wrote ${SCRIPT_PATH}`);
}
